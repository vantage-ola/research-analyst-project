"""Generate the worker survey from data/tasks.csv.

Usage: python3 -I build_survey.py

Writes:
  survey/build_form.gs    Google Apps Script. Paste into script.google.com, run buildForm(),
                          and it creates the Google Form in your account and logs its links.
  survey/preview.md       The same questions as plain text, for review before building.

Each worker picks their main job and only sees that job's tasks, so the form takes about 5 minutes.
No names, phone numbers or emails are collected.
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "survey"

TITLE = "AI and Nigerian remote work: which tasks can AI do?"
INTRO = (
    "I'm studying which parts of common Nigerian remote and freelance jobs AI tools can do today. "
    "You'll rate the tasks in your own job. It takes about 5 minutes.\n\n"
    "There are no right answers. Your experience is the point, and it's fine if you disagree with what AI companies say.\n\n"
    "Your answers are anonymous: no name, phone number or email is collected. Results are published only as totals "
    "and short anonymous quotes. This is an independent study by Olaoluwa Oluwasanya (olaoluwa.work)."
)
CONSENT = "I do this work, I'm 18 or older, and I agree that my anonymous answers can be used in a published study."
RATE_HELP = (
    "Think of the best AI tools you know (ChatGPT, Claude, Gemini, Meta AI and others).\n"
    "For each task: could AI do it well enough that your client would accept the work after a quick check?\n\n"
    "0 = AI can't do much of it. You still do the main work.\n"
    "1 = AI can do part of it or save real time, but you still do or check a lot.\n"
    "2 = AI can do most of it. You'd only need to check it.\n"
    "Pick \"I don't do this\" for tasks that aren't part of your work."
)
COLUMNS = ["0 - AI can't", "1 - AI can do part", "2 - AI can do most", "I don't do this"]
YEARS = ["Less than 1 year", "1 to 2 years", "3 to 5 years", "More than 5 years"]
HOURS = ["Less than 10", "10 to 20", "21 to 40", "More than 40"]
CLIENTS = ["Foreign clients via Upwork, Fiverr or similar", "Foreign clients directly", "Nigerian clients or employer",
           "An AI training or annotation platform", "A BPO or outsourcing company"]
AI_USE = ["Never", "Sometimes", "Often", "For most of my work"]
BARRIERS = ["Cost of paid AI tools, or paying with a Nigerian card", "Internet or power",
            "AI is weak in Nigerian languages, Pidgin or accents", "Clients don't allow AI",
            "I don't trust the output", "I don't know which tools to use", "Nothing stops me"]


def load():
    cats = list(csv.DictReader(open(DATA / "categories.csv", newline="")))
    tasks = list(csv.DictReader(open(DATA / "tasks.csv", newline="")))
    for c in cats:
        c["tasks"] = [t["task"] for t in tasks if t["category_id"] == c["category_id"]]
    return cats


def gs(cats):
    j = json.dumps
    lines = [
        "// Generated by analysis/build_survey.py from data/tasks.csv. Do not edit by hand.",
        "function buildForm() {",
        f"  var form = FormApp.create({j(TITLE)});",
        f"  form.setDescription({j(INTRO)});",
        "  form.setCollectEmail(false);",
        "  form.setLimitOneResponsePerUser(false);",
        "  form.setProgressBar(true);",
        f"  form.addCheckboxItem().setTitle('Consent').setChoiceValues([{j(CONSENT)}]).setRequired(true);",
        "  var job = form.addMultipleChoiceItem().setTitle('Which of these is your main job?').setRequired(true);",
        "  var pages = [];",
    ]
    for c in cats:
        cid = c["category_id"]
        lines += [
            f"  var p_{cid} = form.addPageBreakItem().setTitle({j(c['category'])});",
            f"  pages.push(p_{cid});",
            f"  form.addMultipleChoiceItem().setTitle('How long have you done this work?').setChoiceValues({j(YEARS)}).setRequired(true);",
            f"  form.addMultipleChoiceItem().setTitle('Hours a week on this work').setChoiceValues({j(HOURS)}).setRequired(true);",
            f"  form.addGridItem().setTitle({j('Rate each task in ' + c['category'].lower())}).setHelpText({j(RATE_HELP)})"
            f".setRows({j(c['tasks'])}).setColumns({j(COLUMNS)}).setRequired(true);",
            f"  form.addParagraphTextItem().setTitle('Is there a big task in this job we missed? Would AI manage it?');",
        ]
    lines += [
        "  var common = form.addPageBreakItem().setTitle('About your work and AI');",
        "  // Jump from the end of each job section to the shared section.",
        "  for (var i = 1; i < pages.length; i++) { pages[i].setGoToPage(common); }",
        "  job.setChoices([",
    ]
    lines += [f"    job.createChoice({j(c['category'])}, p_{c['category_id']})," for c in cats]
    lines += [
        "  ]);",
        f"  form.addCheckboxItem().setTitle('Who do you mostly work for?').setChoiceValues({j(CLIENTS)}).showOtherOption(true);",
        f"  form.addMultipleChoiceItem().setTitle('How often do you use AI tools in this work?').setChoiceValues({j(AI_USE)}).setRequired(true);",
        "  form.addCheckboxItem().setTitle('Which AI tools do you use?').setChoiceValues(['ChatGPT', 'Claude', 'Gemini', 'Meta AI (WhatsApp)', 'Copilot', 'Grammarly', 'None']).showOtherOption(true);",
        f"  form.addCheckboxItem().setTitle('What stops you using AI more?').setChoiceValues({j(BARRIERS)}).showOtherOption(true);",
        "  form.addParagraphTextItem().setTitle('Which task has AI changed the most for you, for better or worse?');",
        "  form.addMultipleChoiceItem().setTitle('Has AI changed how much work or pay you get?').setChoiceValues(['Less work or pay', 'No change', 'More work or pay', 'Not sure']);",
        "  Logger.log('Share this link: ' + form.getPublishedUrl());",
        "  Logger.log('Edit the form here: ' + form.getEditUrl());",
        "}",
    ]
    return "\n".join(lines) + "\n"


def preview(cats):
    md = [f"# {TITLE}", "", INTRO, "", f"- [required] {CONSENT}", "- [required] Which of these is your main job? (goes to that job's section)", ""]
    for c in cats:
        md += [f"## {c['category']}", "", f"- How long have you done this work? {' / '.join(YEARS)}",
               f"- Hours a week on this work: {' / '.join(HOURS)}", "", "Rate each task:", "", RATE_HELP, "",
               "| Task | " + " | ".join(COLUMNS) + " |", "|---|" + "---|" * len(COLUMNS)]
        md += [f"| {t} |" + " |" * len(COLUMNS) for t in c["tasks"]]
        md += ["", "- Is there a big task in this job we missed? Would AI manage it? (text)", ""]
    md += ["## About your work and AI (everyone)", "",
           f"- Who do you mostly work for? {' / '.join(CLIENTS)} / Other",
           f"- How often do you use AI tools in this work? {' / '.join(AI_USE)}",
           "- Which AI tools do you use? ChatGPT / Claude / Gemini / Meta AI (WhatsApp) / Copilot / Grammarly / None / Other",
           f"- What stops you using AI more? {' / '.join(BARRIERS)} / Other",
           "- Which task has AI changed the most for you, for better or worse? (text)",
           "- Has AI changed how much work or pay you get? Less / No change / More / Not sure"]
    return "\n".join(md) + "\n"


def main():
    cats = load()
    OUT.mkdir(exist_ok=True)
    (OUT / "build_form.gs").write_text(gs(cats))
    (OUT / "preview.md").write_text(preview(cats))
    print(f"{len(cats)} job sections, {sum(len(c['tasks']) for c in cats)} tasks")


if __name__ == "__main__":
    main()
